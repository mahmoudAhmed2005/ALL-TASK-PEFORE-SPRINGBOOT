/*====================================================
1) NATURAL JOIN
====================================================*/


-- Employees and Department names

SELECT EMP_NAME, DEPT_NAME
FROM EMPLOYEES
NATURAL JOIN DEPARTMENTS;



-- Orders with Customer names

SELECT ORDER_ID, CUSTOMER_NAME
FROM ORDERS
NATURAL JOIN CUSTOMERS;



-- Students and Courses

SELECT STUDENT_NAME, COURSE_NAME
FROM STUDENTS
NATURAL JOIN COURSES;



-- Projects and Employees

SELECT PROJECT_NAME, EMP_NAME
FROM PROJECTS
NATURAL JOIN EMPLOYEES;



-- Invoice details and Products

SELECT INVOICE_ID, PRODUCT_NAME
FROM INVOICES
NATURAL JOIN PRODUCTS;



-- Books and Authors

SELECT BOOK_TITLE, AUTHOR_NAME
FROM BOOKS
NATURAL JOIN AUTHORS;



-- Class schedules and Instructors

SELECT CLASS_DATE, INSTRUCTOR_NAME
FROM SCHEDULES
NATURAL JOIN INSTRUCTORS;



-- Suppliers and Products

SELECT SUPPLIER_NAME, PRODUCT_NAME
FROM SUPPLIERS
NATURAL JOIN PRODUCTS;



-- Customer Orders and Shipping

SELECT ORDER_ID, SHIPPING_DATE
FROM ORDERS
NATURAL JOIN SHIPPING;



-- Employees and Job Titles

SELECT EMP_NAME, JOB_TITLE
FROM EMPLOYEES
NATURAL JOIN JOBS;



