/*====================================================
3) TABLE ALIAS (AMBIGUOUS COLUMNS)
====================================================*/


-- Employee and Manager from same table

SELECT 
E.EMPLOYEE_ID,
E.NAME AS EMPLOYEE_NAME,
M.NAME AS MANAGER_NAME
FROM EMPLOYEES E
JOIN EMPLOYEES M
ON E.MANAGER_ID = M.EMPLOYEE_ID;



-- Customers and Salespersons

SELECT
C.NAME AS CUSTOMER_NAME,
E.NAME AS SALESPERSON_NAME
FROM CUSTOMERS C
JOIN EMPLOYEES E
ON C.SALESPERSON_ID = E.EMPLOYEE_ID;



-- Orders and Order Details

SELECT
O.ORDER_ID,
OD.PRODUCT_ID
FROM ORDERS O
JOIN ORDER_DETAILS OD
ON O.ORDER_ID = OD.ORDER_ID;



-- Students and Instructors

SELECT
S.NAME AS STUDENT_NAME,
I.NAME AS INSTRUCTOR_NAME
FROM STUDENTS S
JOIN INSTRUCTORS I
ON S.INSTRUCTOR_ID = I.INSTRUCTOR_ID;



-- Employee salaries and Department budgets

SELECT
E.NAME,
E.SALARY,
D.BUDGET
FROM EMPLOYEES E
JOIN DEPARTMENTS D
ON E.DEPARTMENT_ID = D.DEPARTMENT_ID;



-- Projects and Tasks

SELECT
P.NAME AS PROJECT_NAME,
T.NAME AS TASK_NAME
FROM PROJECTS P
JOIN TASKS T
ON P.PROJECT_ID = T.PROJECT_ID;



-- Courses and Exams dates

SELECT
C.COURSE_NAME,
C.EXAM_DATE AS COURSE_DATE,
E.EXAM_DATE AS EXAM_DATE
FROM COURSES C
JOIN EXAMS E
ON C.COURSE_ID = E.COURSE_ID;



-- Products and Categories

SELECT
P.NAME AS PRODUCT_NAME,
C.NAME AS CATEGORY_NAME
FROM PRODUCTS P
JOIN CATEGORIES C
ON P.CATEGORY_ID = C.CATEGORY_ID;



-- Books and Publishers

SELECT
B.TITLE AS BOOK_TITLE,
P.NAME AS PUBLISHER_NAME
FROM BOOKS B
JOIN PUBLISHERS P
ON B.PUBLISHER_ID = P.PUBLISHER_ID;



-- Employees and Department Location

SELECT
E.NAME AS EMPLOYEE_NAME,
D.LOCATION AS DEPARTMENT_LOCATION
FROM EMPLOYEES E
JOIN DEPARTMENTS D
ON E.DEPARTMENT_ID = D.DEPARTMENT_ID;